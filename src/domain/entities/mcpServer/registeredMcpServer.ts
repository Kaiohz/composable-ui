import type { McpTransportType } from "@/domain/entities/agent/mcpServerConfig";

/**
 * How a registered MCP server is provisioned.
 *
 * - `"external"` — a remote MCP server reachable over HTTP/STDIO.
 * - `"openapi"` — an MCP server mounted from an OpenAPI spec.
 */
export type McpSourceType = "external" | "openapi";

/**
 * How the registry forwards credentials to a registered MCP server (REQ-004).
 *
 * - `"headers"` (default) — the configured headers are sent as-is.
 * - `"user_token"` — the backend injects the connected user's credential at
 *   load/validate time (`Authorization: Bearer ${USER_JWT}` when the caller is
 *   authenticated via OAuth/JWT, `X-API-Key: ${USER_API_KEY}` via API key).
 *   No secret is stored or transmitted for this mode.
 */
export type McpAuthMode = "headers" | "user_token";

/**
 * A registered MCP server as stored in the central registry.
 *
 * The backend returns a *masked* representation on list/get (secrets stripped
 * to `null` / empty objects; `auth_mode` is echoed as non-secret metadata once
 * the registry persists it — optional until then, see {@link auth_mode}); the
 * *revealed* representation (via the `/reveal` endpoint) populates `auth_token`,
 * `headers`, and `env` in plaintext. Both shapes share the same interface —
 * the only difference is whether the secret fields are populated.
 */
export interface RegisteredMcpServer {
  /** Unique server name (also the registry key). */
  readonly name: string;
  /** Transport used to reach the server (STDIO or HTTP). */
  readonly transport: McpTransportType;
  /** Endpoint URL for HTTP transports; empty for STDIO. */
  readonly url: string;
  /** HTTP headers to send. `{}` when masked. */
  readonly headers: Record<string, string>;
  /** Environment variables. `{}` when masked. */
  readonly env: Record<string, string>;
  /** Auth token. `null` when masked; plaintext when revealed. */
  readonly auth_token: string | null;
  /** Number of tools exposed by the server. */
  readonly tool_count: number;
  /** ISO timestamp — registry creation time. */
  readonly created_at: string;
  /** ISO timestamp — last registry update. */
  readonly updated_at: string;
  /** How the server is provisioned (`"external"` remote MCP, `"openapi"` spec-mounted). */
  readonly source_type: McpSourceType;
  /** URL of the OpenAPI spec. `null` for `"external"` servers. */
  readonly openapi_url: string | null;
  /**
   * How the backend forwards credentials (REQ-004, default `"headers"`).
   *
   * OPTIONAL on the READ projection: the field only travels on the wire once
   * the registry persists and echoes it (REQ-004 rollout). `undefined` means
   * UNKNOWN — read defensively (`entry.auth_mode ?? "headers"`) for display
   * defaults, and NEVER re-send a guessed mode on update (an unrelated edit
   * would silently downgrade a stored `user_token` server). Write payloads
   * ({@link McpServerInput}) keep the field REQUIRED.
   */
  readonly auth_mode?: McpAuthMode;
}

/**
 * Full payload for create / validate operations against the registry. Secrets
 * are sent in plaintext; the backend masks them on the response. The legacy
 * `auth_token` field is NOT part of the payload (REQ-005: the stored token,
 * if any, is forwarded by the backend as the `Authorization` header).
 *
 * For `source_type="openapi"`, `url` MUST be `null` (the mounted URL is
 * generated by the backend). For `source_type="external"`, it is a string.
 */
export interface McpServerInput {
  readonly name: string;
  readonly url: string | null;
  readonly headers: Record<string, string>;
  readonly env: Record<string, string>;
  readonly auth_mode: McpAuthMode;
  /** How the server is provisioned (`"external"` remote MCP, `"openapi"` spec-mounted). */
  readonly source_type: McpSourceType;
  /** URL of the OpenAPI spec. `null` for `"external"` servers. */
  readonly openapi_url: string | null;
}

/**
 * Partial update payload (REQ-019): the backend merges updates with
 * `exclude_unset` semantics, so a key ABSENT from the payload preserves the
 * stored secret. Untouched secret fields (headers/env) must therefore be
 * omitted entirely — never sent as empty values, which would clear them
 * (REQ-016: the edit dialog works from the masked projection). The
 * `-readonly` modifier mirrors the wire payload: builders fill these
 * conditionally (the entity above keeps `readonly` to protect consumers).
 */
export type McpServerUpdateInput = {
  -readonly [K in keyof McpServerInput]?: McpServerInput[K];
};

/**
 * Payload for a validate ("Test connection") call against the registry
 * (`POST /servers/validate`).
 *
 * - Create mode: a FULL {@link McpServerInput} candidate — every field
 *   present, `server_id` absent; the backend probes it unchanged.
 * - Edit mode (`server_id` set): the backend MERGES the stored entry's
 *   secrets into the candidate before probing, so untouched masked fields
 *   (REQ-018) are OMITTED with the same partial semantics as
 *   {@link McpServerUpdateInput} — a present-empty value would override its
 *   merged stored counterpart and probe the entry WITHOUT its stored
 *   credential (BUG-001: a false "unreachable"/401 on stored-credential
 *   servers, since the masked projection never carries the secret).
 */
export type McpServerValidateInput = McpServerUpdateInput & {
  /** Registry key of the stored entry whose secrets merge into the probe candidate (edit mode). */
  readonly server_id?: string;
};

/**
 * Would switching the edit dialog's authentication mode from
 * {@link openedAuthMode} — the server's stored mode when the dialog opened —
 * to {@link nextAuthMode} WIPE a stored credential on save (M-2)?
 *
 * Pure domain rule. The destructive boundary is `user_token`: entering it
 * from any other stored mode (`"headers"`, or an UNKNOWN mode whose stored
 * state the UI cannot see) clears the static credential on save
 * (`authModeCrossed`), and leaving it for `"headers"` clears the
 * user_token-era credential. `undefined → "headers"` is the ONE safe
 * transition (M-3): the stored state is unknown and untouched — the update
 * payload changes nothing stored. The UI cannot see stored secrets (masked
 * projection, REQ-016/REQ-018), so the gate CONFIRMS only transitions that
 * actually wipe on save; every destructive save path crosses one of them
 * exactly once (the opened-mode anchor makes a revert-to-initial move a
 * no-op rather than a second wipe).
 */
export function authModeSwitchWipesStoredCredential(
  openedAuthMode: McpAuthMode | undefined,
  nextAuthMode: McpAuthMode,
): boolean {
  if (nextAuthMode === openedAuthMode) {
    return false;
  }
  if (nextAuthMode === "user_token") {
    return openedAuthMode !== "user_token";
  }
  // next === "headers"
  return openedAuthMode === "user_token";
}

/** Result of a validation (test connection) call. */
export interface McpServerValidationResult {
  readonly tool_count: number;
}
